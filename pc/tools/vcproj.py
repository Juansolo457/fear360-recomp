"""Turn the public tools' VS2003 project files into a CMake source list.

The F.E.A.R. public tools (v1.08) ship their game code with VS .NET 2003 projects
(.vcproj 7.10). Modern Visual Studio can't open those, so this reads the file list,
include directories and defines of one configuration from each project and writes
them as CMake variables. Nothing from the SDK is copied into this repo: the output
goes to the build folder and names files in the user's own SDK tree.

Usage: python -I vcproj.py <sdk root> <configuration> <out .cmake>
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

# CMake name -> project file, relative to the SDK root.
PROJECTS = {
    'Shared_StdLith': 'libs/stdlith/Shared_StdLith.vcproj',
    'Shared_Platform': 'libs/platform/Shared_Platform.vcproj',
    'Game_GUIMgr': 'Game/Libs/LTGUIMgr/Game_GUIMgr.vcproj',
    'Game_Shared_Client': 'Game/Shared/Game_Shared_Client.vcproj',
    'Game_Shared_Server': 'Game/Shared/Game_Shared_Server.vcproj',
    'Game_ClientShell': 'Game/ClientShellDLL/Game_ClientShell.vcproj',
    'Game_ServerShell': 'Game/ObjectDLL/Game_ServerShell.vcproj',
    'Game_ClientFX': 'Game/ClientFxDLL/Game_ClientFX.vcproj',
}

# Defines that only made sense for the 2003 toolchain.
DROP_DEFINES = {'USE_INTEL_COMPILER'}


def cmake_path(p):
    return p.replace('\\', '/')


def resolve(base, rel, root):
    """Resolve a project-relative path; the projects spell 'Engine' and 'engine' both ways."""
    p = os.path.normpath(os.path.join(base, rel.replace('\\', os.sep)))
    if os.path.exists(p):
        return p
    # Case-insensitive walk for trees unpacked on a case-sensitive system.
    parts = os.path.relpath(p, root).split(os.sep)
    cur = root
    for part in parts:
        if part == '..':
            cur = os.path.dirname(cur)
            continue
        names = {n.lower(): n for n in os.listdir(cur)} if os.path.isdir(cur) else {}
        cur = os.path.join(cur, names.get(part.lower(), part))
    return cur


def read_project(root, rel, config):
    path = os.path.join(root, rel)
    base = os.path.dirname(path)
    tree = ET.parse(path)
    cfg_name = f'{config}|Win32'
    cfg = next(c for c in tree.iter('Configuration') if c.get('Name') == cfg_name)
    cl = next(t for t in cfg.iter('Tool') if t.get('Name') == 'VCCLCompilerTool')
    incs = [resolve(base, d.strip().strip('"'), root)
            for d in re.split(r'[;,]', cl.get('AdditionalIncludeDirectories', '')) if d.strip()]
    defs = [d for d in cl.get('PreprocessorDefinitions', '').split(';') if d and d not in DROP_DEFINES]
    sources = []
    for f in tree.iter('File'):
        rp = f.get('RelativePath')
        if not rp or not rp.lower().endswith(('.cpp', '.c')):
            continue
        excluded = any(fc.get('Name') == cfg_name and fc.get('ExcludedFromBuild', '').upper() == 'TRUE'
                       for fc in f.findall('FileConfiguration'))
        if not excluded:
            sources.append(resolve(base, rp, root))
    return sources, incs, defs


def main():
    root, config, out = os.path.abspath(sys.argv[1]), sys.argv[2], sys.argv[3]
    lines = ['# Generated by pc/tools/vcproj.py from the public tools projects. Do not edit.']
    for name, rel in PROJECTS.items():
        sources, incs, defs = read_project(root, rel, config)
        missing = [s for s in sources if not os.path.exists(s)]
        if missing:
            sys.exit(f'{rel}: {len(missing)} listed sources missing, first: {missing[0]}')
        lines.append(f'set({name}_SOURCES')
        lines += [f'  "{cmake_path(s)}"' for s in sources]
        lines.append(')')
        lines.append(f'set({name}_INCLUDES ' + ' '.join(f'"{cmake_path(i)}"' for i in incs) + ')')
        lines.append(f'set({name}_DEFINES ' + ' '.join(defs) + ')')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')


main()
