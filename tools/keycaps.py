# Writes port-nx/src/keycaps.inc: the key caps the menus' button prompts show with the keyboard
# and mouse (port-nx/src/texture_pack.h, built-in replacements): Enter for the 360's A, Esc for
# its B. Our own drawing, a light key with its name, 64x64, in the 360 texture's memory order
# (k_8_8_8_8 read ZYXW: B, G, R, A).
#   python -I tools/keycaps.py
# Needs Pillow and a bold sans font (Windows: Arial Bold).
import os
import sys

from PIL import Image, ImageDraw, ImageFont

SIZE = 64
KEYS = [("kEnter", "Enter"), ("kEsc", "Esc")]
FONTS = [r"C:\Windows\Fonts\arialbd.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"]


def keycap(label):
    scale = 4  # drawn large, then reduced: smooth edges
    s = SIZE * scale
    img = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    pad, radius = 3 * scale, 9 * scale
    # The key's side (darker), then its top face.
    d.rounded_rectangle([pad, pad + 3 * scale, s - pad, s - pad], radius, fill=(120, 120, 124, 255))
    d.rounded_rectangle([pad, pad, s - pad, s - pad - 5 * scale], radius, fill=(226, 226, 230, 255),
                        outline=(150, 150, 156, 255), width=scale)
    font_path = next(p for p in FONTS if os.path.exists(p))
    size = 22 * scale if len(label) <= 3 else 17 * scale
    font = ImageFont.truetype(font_path, size)
    box = d.textbbox((0, 0), label, font=font)
    w, h = box[2] - box[0], box[3] - box[1]
    face_h = s - 2 * pad - 5 * scale
    d.text(((s - w) / 2 - box[0], pad + (face_h - h) / 2 - box[1]), label, font=font,
           fill=(24, 24, 28, 255))
    return img.resize((SIZE, SIZE), Image.LANCZOS)


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, "port-nx", "src", "keycaps.inc")
    lines = ["// Generated by tools/keycaps.py: key caps for the menus' button prompts, "
             f"{SIZE}x{SIZE},", "// B, G, R, A per texel. Our own drawing.", ""]
    for name, label in KEYS:
        px = keycap(label).tobytes()
        bgra = bytearray()
        for i in range(0, len(px), 4):
            r, g, b, a = px[i:i + 4]
            bgra += bytes((b, g, r, a))
        lines.append(f"constexpr uint8_t {name}[{len(bgra)}] = {{")
        for i in range(0, len(bgra), 24):
            lines.append("    " + ",".join(str(v) for v in bgra[i:i + 24]) + ",")
        lines.append("};")
        lines.append("")
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", out)


if __name__ == "__main__":
    sys.exit(main())
